    "    _fitted = np.polyval(_c, x_frn_dr)\n",
    "    _sse = np.sum((y_frn_dr - _fitted) ** 2)\n",
    "    _n   = len(x_frn_dr)\n",
    "    _bic = _n * np.log(_sse / _n + 1e-15) + _d * np.log(_n)\n",
